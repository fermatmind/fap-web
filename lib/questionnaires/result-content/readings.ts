/** Explicit frontend editorial selection; unknown products and identities retain their source report. */
export function getResultReading(slug: string, profile: QuestionnaireProfile) {
  if (!Object.hasOwn(readings, slug)) return null;
  const entry = readings[slug];
  const selected = entry.select(profile);
  return selected === profile ? null : { ...entry, profile: selected };
}

/** Materialise only the selected product on the server; keep the source object untouched. */
export function prepareResultProfile(quizSlug: string, profile: QuestionnaireProfile): QuestionnaireProfile {
  if (profile.resultReading?.quizSlug === quizSlug && profile.resultReading.profileId === profile.id) return profile;
  const reading = getResultReading(quizSlug, profile);
  if (!reading) return profile;
  return {
    ...reading.profile,
    resultReading: {
      quizSlug, profileId: profile.id, attribute: reading.attribute,
      ...(reading.note ? { note: reading.note } : {}),
      ...(reading.references ? { references: reading.references } : {}),
    },
  };
}

export function prepareQuestionnaireResultReadings(quiz: Questionnaire): Questionnaire {
  const profiles = quiz.profiles.map(profile => prepareResultProfile(quiz.slug, profile));
  const guide = quiz.slug === "delulu-test" ? deluluResultSections(quiz.guide) : quiz.guide;
  const questions = quiz.slug === "english-proficiency" ? englishProficiencyResultQuestions(quiz.questions) : quiz.slug === "spanish-proficiency" ? spanishProficiencyResultQuestions(quiz.questions) : quiz.slug === "project-management" ? projectManagementResultQuestions(quiz.questions) : quiz.slug === "problem-solving-critical-thinking" ? problemSolvingResultQuestions(quiz.questions) : quiz.slug === "ai-literacy" ? aiLiteracyResultQuestions(quiz.questions) : quiz.questions;
  return questions === quiz.questions && guide === quiz.guide && profiles.every((profile, index) => profile === quiz.profiles[index]) ? quiz : { ...quiz, profiles, guide, questions };
}
