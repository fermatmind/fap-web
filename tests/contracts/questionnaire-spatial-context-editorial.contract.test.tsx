import { readFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it, vi } from "vitest";
import type { Questionnaire } from "@/lib/questionnaires/types";
import { SpatialContextPage } from "@/components/questionnaires/SpatialContextPage";
import { spatialContextSections, spatialContextFaq, spatialContextReadingSummaries } from "@/components/questionnaires/SpatialContextLandingEditorial";
vi.mock("next/headers", () => ({ headers: async () => new Headers() }));
const quiz = JSON.parse(readFileSync("lib/questionnaires/data/spatial-thinking-reflection.json", "utf8")) as Questionnaire;
describe("spatial-context daily context editorial and complete public landing", () => {
  it.each(["en", "zh"] as const)("retains all source guides and bespoke explanations in %s", locale => {
    const dom=document.createElement("div");dom.innerHTML=renderToStaticMarkup(<SpatialContextPage quiz={quiz} locale={locale} />);
    expect(dom.querySelectorAll("h1")).toHaveLength(1);
    expect(dom.querySelectorAll("[data-spatial-context-separate-resources] li")).toHaveLength(8);
    expect(dom.querySelector("#spatial-context-methods")?.textContent).toBe(locale === "en" ? "Spatial relations: recollection, representation and task methods" : "空间关系：回忆、表征与任务方法");
    expect(dom.querySelectorAll("[data-explore-start]")).toHaveLength(1);
    expect(dom.querySelector(".explore-intro-content [data-explore-start]")).not.toBeNull();
    expect(dom.querySelector("[data-spatial-context-arrangement]")).not.toBeNull();
    expect(dom.querySelectorAll("input[type=checkbox],details p,details section,details article,textarea")).toHaveLength(0);
    expect(dom.querySelectorAll("[data-spatial-context-full-guide]")).toHaveLength(1);
    expect(dom.querySelectorAll('[aria-labelledby="spatial-context-library"] li')).toHaveLength(1);
    expect(dom.querySelectorAll('[aria-labelledby="spatial-context-faq"] h3')).toHaveLength(10);
    for(const p of quiz.profiles) for(const s of p.sections) for(const paragraph of s.paragraphs) expect(dom.textContent).toContain(paragraph[locale]);
    for(const p of quiz.profiles) expect(dom.querySelector('[aria-labelledby="spatial-context-library"]')?.textContent).toContain(spatialContextReadingSummaries[p.id][locale]);
    expect(new Set(Object.values(spatialContextReadingSummaries).map(t=>t[locale])).size).toBe(1);
    expect(spatialContextSections).toHaveLength(8);expect(spatialContextFaq).toHaveLength(8);
    for(const s of spatialContextSections) for(const p of s.paragraphs) expect(dom.textContent).toContain(p[locale]);
    expect(dom.querySelectorAll('[id^="spatial-context-reference-"]')).toHaveLength(1);
    const ids=[...dom.querySelectorAll("[id]")].map(n=>n.id);expect(new Set(ids).size).toBe(ids.length);
  });
});
