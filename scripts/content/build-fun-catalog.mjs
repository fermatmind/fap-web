import { readFile, readdir, writeFile } from 'node:fs/promises';
const root = new URL('../../lib/entertainment/', import.meta.url);
const names = (await readdir(new URL('data/', root))).filter(name => name.endsWith('.json')).sort();
const catalog = [];
for (const name of names) {
  const q = JSON.parse(await readFile(new URL(`data/${name}`, root), 'utf8'));
  const { slug, version, updated, category, title, description, minutes } = q;
  if (name !== `${slug}.json`) throw new Error(`Identity mismatch: ${name}`);
  function depth(id, path = [], shortest = false) {
    if (path.includes(id)) throw new Error(`Cycle in ${slug}`);
    const node = q.questions.find(item => item.id === id);
    if (!node) throw new Error(`Missing branch ${id}`);
    return 1 + (shortest ? Math.min : Math.max)(...node.options.map(option => option.next ? depth(option.next, [...path, id], shortest) : 0));
  }
  const questionCount = q.mechanism === 'branch' ? depth(q.questions[0].id) : q.questions.length;
  const minQuestionCount = q.mechanism === 'branch' ? depth(q.questions[0].id, [], true) : questionCount;
  catalog.push({ slug, version, updated, category, title, description, minutes, questionCount, minQuestionCount });
}
const outputs = {
  'catalog.json': `${JSON.stringify(catalog, null, 2)}\n`,
  'loaders.ts': `// Generated by scripts/content/build-fun-catalog.mjs. Server imports only.\nimport type { FunQuiz } from './types';\nconst loaders: Record<string, () => Promise<{default: unknown}>> = {\n${catalog.map(q => `  "${q.slug}": () => import("./data/${q.slug}.json"),`).join('\n')}\n};\nexport async function loadFunQuiz(slug: string): Promise<FunQuiz | null> {\n  const loader = Object.hasOwn(loaders, slug) ? loaders[slug] : undefined;\n  return loader ? (await loader()).default as FunQuiz : null;\n}\n`,
};
for (const [name, value] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (await readFile(new URL(name, root), 'utf8') !== value) throw new Error(`Stale ${name}`);
  } else await writeFile(new URL(name, root), value);
}
console.log(`${catalog.length} independent entertainment products; bilingual catalog current`);
